import test from 'node:test';
import assert from 'node:assert/strict';
import { validBody, validCommit } from '../scripts/pr-metadata.js';

const person = { name: 'Dawson McThay WGU', email: 'dmctha2@wgu.edu' };
const commit = { author: person, committer: person, message: 'Add bridge' };
const footer = 'Requested by **mcthaydt**';
test('PR body must end in the exact owner footer and omit generated attribution', () => {
  assert.ok(validBody('Fix\r\n' + footer + '\r\n'));
  for (const body of [null, footer + '\nother', 'Generated with AI\n' + footer, 'Generated by Foo\n' + footer]) assert.equal(validBody(body), false);
});
test('both commit identities and attribution are checked', () => {
  assert.ok(validCommit(commit));
  for (const field of ['author', 'committer']) assert.equal(validCommit({ ...commit, [field]: { ...person, email: 'other@example.com' } }), false);
  for (const line of ['Co-authored-by: Claude <other@example.com>', 'Claude-Session: test', 'Generated with Claude Code']) assert.equal(validCommit({ ...commit, message: 'Fix\n\n' + line }), false);
});
